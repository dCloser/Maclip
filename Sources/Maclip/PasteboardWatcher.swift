import AppKit

/// Polls the general pasteboard (macOS has no change notification) and reports new text
/// or images (e.g. a screenshot taken with Control held, or "Copy Image" in a browser).
@MainActor
final class PasteboardWatcher {
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let onText: (String) -> Void
    private let onImage: (_ png: Data, _ width: Int, _ height: Int) -> Void

    /// Marker types set by password managers and other apps for data that should not be
    /// recorded by clipboard history tools (see nspasteboard.org).
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init(onText: @escaping (String) -> Void,
         onImage: @escaping (_ png: Data, _ width: Int, _ height: Int) -> Void) {
        self.onText = onText
        self.onImage = onImage
        // Start one behind so whatever is on the clipboard at launch gets recorded too.
        lastChangeCount = pasteboard.changeCount - 1
    }

    func start() {
        timer?.invalidate()
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        poll()
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        // Prefer text: apps like Excel or Word also put a picture of the selection on the
        // pasteboard, but the user copied text.
        if let text = pasteboard.string(forType: .string) {
            onText(text)
        } else if let image = Self.pngData(from: pasteboard) {
            onImage(image.png, image.width, image.height)
        }
    }

    /// The pasteboard's image as PNG data, converting from TIFF when needed.
    static func pngData(from pasteboard: NSPasteboard) -> (png: Data, width: Int, height: Int)? {
        if let png = pasteboard.data(forType: .png), let rep = NSBitmapImageRep(data: png) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        if let tiff = pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        return nil
    }
}
